// @ts-expect-error Public command fixture shared with the real Worker journey.
import { substituteScenario } from '../api/supplier-substitutes-fixture.mjs'
import { ownerEntry } from './session'
import { test, expect } from '@playwright/test'
import { join } from 'node:path'

test('owners inspect supplier substitute evidence, refuse stale review and retain recommendation decisions', async ({ page }) => {
  test.setTimeout(180_000)
  await page.setViewportSize({ width: 1440, height: 1000 })
  const origin = await ownerEntry(page)
  const command = async (type: string, payload: object) => {
    const response = await page.request.post(origin + '/api/pier/commands', { data: { commandId: crypto.randomUUID(), type, payload }, headers: { origin } })
    const body = await response.json()
    expect(body.ok, JSON.stringify(body)).toBe(true)
    return body.result
  }
  const b = await substituteScenario({ command }, 'synthetic-pier-ui')
  await page.goto(origin + '/app#activity')
  await page.getByText('Substitute settings', { exact: true }).click()
  const mapping = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Exact substitute mapping', exact: true }) }).last()
  await mapping.getByLabel('Original SKU', { exact: true }).selectOption(b.item.id)
  await mapping.getByLabel('Exact alternative SKU', { exact: true }).selectOption(b.incompatible.id)
  await mapping.getByLabel('Equivalence reason').fill('Owner checked the base unit.')
  const submit = async (button: ReturnType<typeof page.getByRole>, success: boolean) => {
    const [response] = await Promise.all([page.waitForResponse(response => response.url() === origin + '/api/pier/commands' && response.request().method() === 'POST', { timeout: 15_000 }), button.click()])
    const body = await response.json()
    expect(body.ok).toBe(success)
    await expect(page.locator('main')).toHaveAttribute('aria-busy', 'false')
    return body
  }
  const invalid = await submit(mapping.getByRole('button', { name: 'Record exact mapping', exact: true }), false)
  expect(invalid.error.code).toBe('SUBSTITUTE_MAPPING')
  await expect(page.getByRole('alert')).toContainText('exact same base unit')
  await mapping.getByLabel('Exact alternative SKU', { exact: true }).selectOption(b.alternative.id)
  await submit(mapping.getByRole('button', { name: 'Record exact mapping', exact: true }), true)
  const prepare = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Compare supplier substitutes', exact: true }) }).last()
  await prepare.getByLabel('Delayed confirmed purchase').selectOption(b.po.id)
  await submit(prepare.getByRole('button', { name: 'Prepare substitute comparison', exact: true }), true)
  let comparison = page.locator('section[aria-label^="Substitute comparison "]').last()
  await expect(comparison).toContainText('uncovered demand 3')
  await expect(comparison).toContainText('uncovered demand 2')
  await expect(comparison).toContainText('No active exact owner mapping.')
  const north = comparison.getByRole('row').filter({ hasText: 'North' }).first()
  await expect(north.getByRole('cell').nth(3)).toHaveText('10')
  await expect(north.getByRole('cell').nth(4)).toHaveText('3')
  await expect(north.getByRole('cell').nth(5)).toHaveText('2')
  await expect(north.getByRole('cell').nth(6)).toHaveText('5')
  await comparison.getByText('Exact source evidence', { exact: true }).click()
  await expect(comparison.getByRole('link').filter({ hasText: b.po.confirmation.replyId }).first()).toHaveAttribute('href', /^\/api\/pier\/export\?source=purchaseOrders&/)
  await expect(comparison.getByRole('link').filter({ hasText: b.hold.id }).first()).toBeVisible()
  const supplierLink = await comparison.getByRole('link').filter({ hasText: b.po.confirmation.replyId }).first().getAttribute('href')
  const supplierSource = await page.request.get(origin + supplierLink)
  expect(supplierSource.status()).toBe(200)
  expect((await supplierSource.json()).record.confirmation.replyId).toBe(b.po.confirmation.replyId)
  const changed = await command('channel.release', { holdId: b.hold.id, version: b.hold.version })
  expect(changed.releasedAt).toBeTruthy()
  await comparison.getByLabel('Recommendation decision').selectOption('accepted')
  await comparison.getByLabel('Review reason', { exact: true }).fill('Check the retained recommendation.')
  await comparison.getByLabel('Confirm recommendation only', { exact: true }).check()
  const stale = await submit(comparison.getByRole('button', { name: 'Record recommendation decision', exact: true }), false)
  expect(stale.error.code).toBe('STALE')
  await expect(page.getByRole('alert')).toContainText('Prepare again')
  await submit(comparison.getByRole('button', { name: 'Prepare again from current inputs', exact: true }), true)
  comparison = page.locator('section[aria-label^="Substitute comparison "]').last()
  await expect(comparison).toContainText('uncovered demand 1')
  await comparison.getByLabel('Recommendation decision').selectOption('declined')
  await comparison.getByLabel('Review reason', { exact: true }).fill('Retain the existing commitment.')
  await comparison.getByLabel('Confirm recommendation only', { exact: true }).check()
  await submit(comparison.getByRole('button', { name: 'Record recommendation decision', exact: true }), true)
  await expect(comparison).toContainText('declined this recommendation')
  await prepare.getByLabel('Delayed confirmed purchase').selectOption(b.po.id)
  await submit(prepare.getByRole('button', { name: 'Prepare substitute comparison', exact: true }), true)
  comparison = page.locator('section[aria-label^="Substitute comparison "]').last()
  await comparison.getByLabel('Recommendation decision').selectOption('accepted')
  await comparison.getByLabel('Review reason', { exact: true }).fill('Accept the comparison without changing the order.')
  await comparison.getByLabel('Confirm recommendation only', { exact: true }).check()
  await submit(comparison.getByRole('button', { name: 'Record recommendation decision', exact: true }), true)
  await expect(comparison).toContainText('accepted this recommendation')
  await page.reload()
  await expect(page.locator('section[aria-label^="Substitute comparison "]').last()).toContainText('accepted this recommendation')
  if (process.env.PIER_SCREENSHOTS) for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.getByText('Substitute settings', { exact: true }).click()
    await mapping.screenshot({ path: join(process.env.PIER_SCREENSHOTS, `${width}-substitute-settings.png`) })
    await comparison.screenshot({ path: join(process.env.PIER_SCREENSHOTS, `${width}-supplier-substitutes.png`) })
    await page.getByText('Substitute settings', { exact: true }).click()
  }
})
